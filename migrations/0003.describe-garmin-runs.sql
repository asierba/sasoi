COMMENT ON TABLE garmin_runs IS 'One row per run recorded on a Garmin watch.';
COMMENT ON COLUMN garmin_runs.activity_id IS 'Garmin activity id.';
COMMENT ON COLUMN garmin_runs.activity_type IS 'running, treadmill_running, trail_running or another Garmin running type.';
COMMENT ON COLUMN garmin_runs.name IS 'Title given to the run in Garmin Connect.';
COMMENT ON COLUMN garmin_runs.start_time_local IS 'Start time in the timezone where the run happened. Use for dates and weekdays.';
COMMENT ON COLUMN garmin_runs.start_time_utc IS 'Start time in UTC.';
COMMENT ON COLUMN garmin_runs.distance_m IS 'Distance in metres.';
COMMENT ON COLUMN garmin_runs.duration_s IS 'Elapsed time in seconds, including pauses.';
COMMENT ON COLUMN garmin_runs.moving_duration_s IS 'Time moving in seconds, excluding pauses.';
COMMENT ON COLUMN garmin_runs.avg_speed_mps IS 'Average speed in metres per second. Pace in seconds per km is 1000 / avg_speed_mps.';
COMMENT ON COLUMN garmin_runs.max_speed_mps IS 'Maximum speed in metres per second.';
COMMENT ON COLUMN garmin_runs.avg_hr IS 'Average heart rate in beats per minute. Null when no heart rate was recorded.';
COMMENT ON COLUMN garmin_runs.max_hr IS 'Maximum heart rate in beats per minute.';
COMMENT ON COLUMN garmin_runs.hr_zone_1_s IS 'Seconds in heart rate zone 1 (easiest), as set in Garmin Connect.';
COMMENT ON COLUMN garmin_runs.hr_zone_2_s IS 'Seconds in heart rate zone 2.';
COMMENT ON COLUMN garmin_runs.hr_zone_3_s IS 'Seconds in heart rate zone 3.';
COMMENT ON COLUMN garmin_runs.hr_zone_4_s IS 'Seconds in heart rate zone 4.';
COMMENT ON COLUMN garmin_runs.hr_zone_5_s IS 'Seconds in heart rate zone 5 (hardest).';
COMMENT ON COLUMN garmin_runs.avg_cadence_spm IS 'Average cadence in steps per minute. 0 when not recorded.';
COMMENT ON COLUMN garmin_runs.max_cadence_spm IS 'Maximum cadence in steps per minute. 0 when not recorded.';
COMMENT ON COLUMN garmin_runs.elevation_gain_m IS 'Total ascent in metres.';
COMMENT ON COLUMN garmin_runs.elevation_loss_m IS 'Total descent in metres.';
COMMENT ON COLUMN garmin_runs.aerobic_training_effect IS 'Garmin aerobic training effect, 0 to 5.';
COMMENT ON COLUMN garmin_runs.anaerobic_training_effect IS 'Garmin anaerobic training effect, 0 to 5.';
COMMENT ON COLUMN garmin_runs.training_load IS 'Garmin training load (EPOC based) for this run.';
COMMENT ON COLUMN garmin_runs.vo2max IS 'Garmin VO2 max estimate in ml/kg/min after this run. Null when the watch gave none.';
COMMENT ON COLUMN garmin_runs.lap_count IS 'Number of laps; matches the rows in garmin_laps.';

COMMENT ON TABLE garmin_laps IS 'Laps of each run, auto laps (usually every km) or manual and workout steps.';
COMMENT ON COLUMN garmin_laps.activity_id IS 'The run this lap belongs to (garmin_runs.activity_id).';
COMMENT ON COLUMN garmin_laps.lap_index IS 'Position in the run, starting at 1.';
COMMENT ON COLUMN garmin_laps.start_time_utc IS 'Lap start time in UTC.';
COMMENT ON COLUMN garmin_laps.distance_m IS 'Distance in metres.';
COMMENT ON COLUMN garmin_laps.duration_s IS 'Elapsed time in seconds.';
COMMENT ON COLUMN garmin_laps.avg_speed_mps IS 'Average speed in metres per second. Pace in seconds per km is 1000 / avg_speed_mps.';
COMMENT ON COLUMN garmin_laps.max_speed_mps IS 'Maximum speed in metres per second.';
COMMENT ON COLUMN garmin_laps.avg_hr IS 'Average heart rate in beats per minute.';
COMMENT ON COLUMN garmin_laps.max_hr IS 'Maximum heart rate in beats per minute.';
COMMENT ON COLUMN garmin_laps.avg_cadence_spm IS 'Average cadence in steps per minute. 0 when not recorded.';
COMMENT ON COLUMN garmin_laps.elevation_gain_m IS 'Ascent in metres.';
COMMENT ON COLUMN garmin_laps.elevation_loss_m IS 'Descent in metres.';
COMMENT ON COLUMN garmin_laps.intensity_type IS 'Workout step: WARMUP, ACTIVE, INTERVAL, RECOVERY, REST or COOLDOWN. Null for laps outside a structured workout.';
